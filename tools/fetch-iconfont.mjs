/**
 * Downloads the editor's two icon fonts into public/iconfont/ and writes the
 * stylesheet the app loads.
 *
 * These are iconfont.cn projects, and their CSS used to be fetched from
 * at.alicdn.com on every page load. That put a third-party CDN in the critical
 * path of an app that otherwise runs offline: when it was slow or blocked,
 * every button in the toolbar rendered as a blank square. Run this after
 * changing either project on iconfont.cn.
 */
import fs from 'node:fs/promises'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const OUT = path.join(ROOT, 'public', 'iconfont')

/** css url, the local basename to save the font as, and what it is */
const PROJECTS = [
  ['https://at.alicdn.com/t/font_2717063_ypy8vprc3b.css?display=swap', 'iconfont', 'toolbar and formatting icons (project 2717063)'],
  ['https://at.alicdn.com/t/c/font_3228074_xojoer6zhp.css', 'icon', 'panel and widget icons (project 3228074)'],
]

async function get(url) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`)
  return res
}

const parts = ['/*', ' * Editor icon fonts, served from here rather than at.alicdn.com.', ' *', ' * Generated by tools/fetch-iconfont.mjs — edit that, not this.', ' */', '']

await fs.mkdir(OUT, { recursive: true })

for (const [cssUrl, name, what] of PROJECTS) {
  const css = await (await get(cssUrl)).text()
  const woff2 = css.match(/url\('(\/\/[^']*\.woff2[^']*)'\)/)?.[1]
  if (!woff2) throw new Error(`no woff2 in ${cssUrl}`)

  const bytes = Buffer.from(await (await get(`https:${woff2}`)).arrayBuffer())
  await fs.writeFile(path.join(OUT, `${name}.woff2`), bytes)

  // One local woff2 replaces the CDN's woff2/woff/ttf/svg list. browserslist is
  // Chrome >= 90, so the older formats were dead weight even before this.
  parts.push(`/* ${what} */`)
  parts.push(css.replace(/src:\s*url\([^)]*\)[^;]*;/, `src: url('./${name}.woff2') format('woff2');`).trim(), '')
  console.log(`  ${name}.woff2  ${(bytes.length / 1024).toFixed(1)}kB  ${what}`)
}

await fs.writeFile(path.join(OUT, 'iconfont.css'), parts.join('\n'))
console.log(`\n  Wrote ${path.relative(ROOT, path.join(OUT, 'iconfont.css'))}\n`)
